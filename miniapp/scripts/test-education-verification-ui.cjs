const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')
const read = file => fs.readFileSync(path.resolve(__dirname, '../src', file), 'utf8')

test('E05：CHSI 与其他方式均有可操作的学历选择及字段错误区域', () => {
  const page = read('pages/verification/components/EducationSubmitPage.tsx')
  assert.match(page, /useEducationVerification/)
  assert.match(page, /education-field-educationLevel/)
  assert.match(page, /educationLevel:\s*form\.draft\.educationLevel/)
  assert.match(page, /<ChsiForm\s+\{\.\.\.fieldProps\}/)
  assert.match(page, /education-field-school/)
  assert.match(page, /issue\.field|issues\.find/)
})
test('E07/E15：材料有独立删除替换控件，原因与操作区不再固定漂移', () => {
  const page = read('pages/verification/components/EducationSubmitPage.tsx')
  assert.match(page, /education-material-remove/)
  assert.match(page, /education-material-replace/)
  assert.match(page, /previewStatus/)
  assert.match(page, /education-status-notice/)
  assert.doesNotMatch(page, /top:\s*'1310rpx'/)
  assert.match(page, /<SubmitButton[\s\S]*?flow/)
  assert.match(page, /<AgreementRow[\s\S]*?flow/)
})
test('E02：输入编辑和候选点选使旧请求失效，确认状态有重选入口', () => {
  const input = read('components/SchoolSearchInput.tsx')
  assert.match(input, /selectionRequired/)
  assert.match(input, /onReselect|reselect/)
  assert.ok(input.indexOf('++requestId.current') < input.indexOf('keyword.length < 2'))
})
test('E10/E15：认证中心刷新最新状态，成功文案不再错写头像', () => {
  const center = read('pages/verification/components/VerificationCenterPage.tsx')
  const success = read('pages/verification/education-submit-success.tsx')
  assert.match(center, /useDidShow/)
  assert.match(center, /education_resubmit_action/)
  assert.match(success, /education_submit_success_notice/)
  assert.doesNotMatch(success, /你的头像正在审核/)
})
